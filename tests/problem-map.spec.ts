import {test,expect} from "@playwright/test";
test("mobile student builds a problem map without typing and shares checkpoint",async({page})=>{
 await page.goto("/learn.html");
 await expect(page.getByRole("link",{name:/בונים מפת שאלה/})).toBeVisible();
 await page.getByRole("link",{name:/בונים מפת שאלה/}).click();
 await expect(page).toHaveURL(/problem-map\.html/);
 await expect(page.getByRole("heading",{name:"מפת השאלה"})).toBeVisible();
 await expect(page.locator("#clarityTrack")).toHaveAttribute("aria-valuenow","0");
 await page.locator('[data-clue="function"]').click();
 await page.locator('[data-clue="extrema"]').click();
 await page.locator('[data-clue="kind"]').click();
 await expect(page.locator("#clarityTrack")).toHaveAttribute("aria-valuenow","3");
 await page.locator('[data-node="derivative"]').click();
 await page.locator('[data-certainty="sure"]').click();
 await expect(page.locator("#clarityTrack")).toHaveAttribute("aria-valuenow","3");
 await page.locator("#checkMap").click();
 await expect(page.locator("#clarityTrack")).toHaveAttribute("aria-valuenow","4");
 await page.locator('[data-before="down"]').click();
 await page.locator('[data-after="up"]').click();
 await expect(page.locator("#localVerdict")).toContainText("מינימום");
 await page.locator("#checkLocal").click();
 await expect(page.locator("#localCheck")).toContainText("התנהגות מקומית");
 await page.locator('[data-before="up"]').click();
 await page.locator('[data-after="up"]').click();
 await expect(page.locator("#localVerdict")).toContainText("אינו מבטיח קיצון");
 await page.locator('[data-checkpoint="unsure"]').click();
 await expect(page.locator("#checkpointSummary")).toContainText("בסדר");
 await page.reload();
 await expect(page.locator('[data-checkpoint="unsure"]')).toHaveAttribute("aria-pressed","true");
 await page.screenshot({path:"test-results/problem-map-mobile.png",fullPage:true});
 const widths=await page.evaluate(()=>({vw:window.innerWidth,scroll:document.documentElement.scrollWidth}));
 expect(widths.scroll).toBeLessThanOrEqual(widths.vw+4);
 await expect(page.locator("#shareCard")).toBeVisible();
});
