 await expect(page.locator('#flowRows .flow-layer')).toHaveCount(0);
 await page.locator('[data-flow-answer="1"]').click();
 await expect(page.locator('#flowRows [data-flow-layer="x-meaning"]')).toContainText('x₀ = 2');
 await page.locator('#flowNext').click();
 await page.locator('[data-flow-answer="0"]').click();
 await expect(page.locator('#flowRows [data-flow-layer="point"]')).toContainText('(2, f(2))');
 await expect(page.locator('#flowRows .flow-layer')).toHaveCount(2);
 await page.reload();
 await expect(page.locator('#flowRows .flow-layer')).toHaveCount(2);
 await expect(page.locator('#flowQuestion')).toContainText('נרשום את נקודת הקיצון');
 await page.locator('#flowNext').click();
 await expect(page.locator('#flowQuestion')).toContainText('f′(x)');
 await page.locator('[data-flow-answer="1"]').click();
 await page.locator('#flowNext').click();
 await page.locator('[data-flow-answer="1"]').click();
 await page.locator('#flowNext').click();
 await page.locator('[data-flow-answer="1"]').click();
 await expect(page.locator('#flowRows [data-flow-layer="differentiate"]')).toContainText('2x + a');
 await page.locator('#flowNext').click();
 await expect(page.locator('#flowQuestion')).toContainText('איפה מציבים');
 await page.locator('[data-flow-answer="1"]').click();
